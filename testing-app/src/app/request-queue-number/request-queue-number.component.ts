import { Component, OnInit } from '@angular/core';
import { DomSanitizer, SafeHtml } from '@angular/platform-browser';
import { MatSnackBar } from '@angular/material/snack-bar';
import { environment } from '../../environments/environment';
import { ApiService } from '../shared/api.service';
import { errorMessage } from '../shared/error-message';
import { QueueTicket } from '../shared/models';
import { printTicket, ticketHtml, TICKET_CSS } from '../shared/ticket';

// Ticket styles are added once to the page so the on-screen preview looks like the printout.
function ensureTicketStyles() {
  if (!document.getElementById('ticket-styles')) {
    const style = document.createElement('style');
    style.id = 'ticket-styles';
    style.textContent = TICKET_CSS;
    document.head.appendChild(style);
  }
}

@Component({
  selector: 'app-request-queue-number',
  templateUrl: './request-queue-number.component.html',
  styleUrls: ['./request-queue-number.component.css']
})
export class RequestQueueNumberComponent implements OnInit {
  hospitalName = environment.hospitalName;
  ticket: QueueTicket;
  ticketPreview: SafeHtml;
  queue: QueueTicket[] = [];
  columns = ['queueNumber', 'createdAt', 'status', 'action'];
  loading = false;
  autoPrint = true;

  constructor(
    private api: ApiService,
    private sanitizer: DomSanitizer,
    private snackBar: MatSnackBar
  ) { }

  get waitingCount(): number {
    return this.queue.filter(q => q.status === 'waiting').length;
  }

  ngOnInit(): void {
    ensureTicketStyles();
    this.loadQueue();
  }

  loadQueue() {
    this.api.getTodayQueue().subscribe(
      list => this.queue = list.reverse(),
      err => this.showError(errorMessage(err))
    );
  }

  takeNumber() {
    this.loading = true;
    this.api.takeQueueNumber().subscribe(
      ticket => {
        this.loading = false;
        this.ticket = ticket;
        // Safe: the HTML is generated by our own code, not by user input.
        this.ticketPreview = this.sanitizer.bypassSecurityTrustHtml(ticketHtml(ticket, this.hospitalName));
        this.queue = [ticket, ...this.queue];
        if (this.autoPrint) {
          this.print(ticket);
        }
      },
      err => {
        this.loading = false;
        this.showError(errorMessage(err));
      }
    );
  }

  print(ticket: QueueTicket = this.ticket) {
    if (ticket) {
      printTicket(ticket, this.hospitalName);
    }
  }

  private showError(message: string) {
    this.snackBar.open(message, 'Close', { duration: 5000, panelClass: 'snack-error' });
  }
}
